using System.Windows.Forms;
using PharmacyStock.Diagnostics;

namespace PharmacyStock.Desktop;

/// <summary>
/// Ten Percent Discount Pharmacy - Stock Manager.
///
/// A normal Windows desktop program. It reads stock from the pharmacy system and warns
/// when a medicine falls below the shelf level you set. It NEVER writes to the pharmacy
/// system - its own data lives in a separate file under %LOCALAPPDATA%.
/// </summary>
internal static class Program
{
    [STAThread]
    private static void Main()
    {
        // Two copies running would mean two sets of notifications for the same shortage.
        using var onlyOneCopy = new Mutex(initiallyOwned: true, "TenPercentStockManager.SingleInstance", out var isFirst);
        if (!isFirst)
        {
            MessageBox.Show(
                "Stock Manager is already running.\r\n\r\n" +
                "Look for the green cross icon near the clock, at the bottom-right of the screen, " +
                "and double-click it.",
                "Stock Manager", MessageBoxButtons.OK, MessageBoxIcon.Information);
            return;
        }

        // Normally generated by the WinForms SDK; set by hand because this project
        // references WinForms directly.
        Application.SetHighDpiMode(HighDpiMode.SystemAware);
        Application.EnableVisualStyles();
        Application.SetCompatibleTextRenderingDefault(false);

        // A desktop program has no console, so an unhandled error would otherwise vanish.
        Application.ThreadException += (s, e) => Fatal("Unexpected error", e.Exception);
        AppDomain.CurrentDomain.UnhandledException += (s, e) => Fatal("Unexpected error", e.ExceptionObject as Exception);

        try
        {
            Log.Info("Stock Manager starting");
            var services = new AppServices();
            Application.Run(new MainForm(services));
            Log.Info("Stock Manager closed");
        }
        catch (Exception ex)
        {
            Fatal("Stock Manager could not start", ex);
        }
    }

    private static void Fatal(string title, Exception? ex)
    {
        Log.Error(title, ex);

        MessageBox.Show(
            title + "\r\n\r\n" +
            (ex?.Message ?? "Unknown error") + "\r\n\r\n" +
            "Details have been written to:\r\n" + Log.FilePath,
            "Stock Manager", MessageBoxButtons.OK, MessageBoxIcon.Error);
    }
}
